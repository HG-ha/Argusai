"""Controlled local PoC page writer/opener for assistant-generated HTML."""

from __future__ import annotations

import html
import re
import time
import uuid
import webbrowser
from pathlib import Path
from typing import Any

from argusai.core.settings import SettingsManager, default_poc_pages_dir


MAX_HTML_CHARS = 200_000
MAX_TITLE_CHARS = 80


def _safe_slug(value: str, default: str = "poc") -> str:
    slug = re.sub(r"[^a-zA-Z0-9_.-]+", "-", (value or "").strip())[:MAX_TITLE_CHARS]
    return slug.strip(".-") or default


def _poc_dir(base_dir: str = "") -> Path:
    if base_dir:
        root = Path(base_dir).expanduser()
    else:
        try:
            root = Path(SettingsManager().get().poc_pages_dir).expanduser()
        except Exception:
            root = Path(default_poc_pages_dir()).expanduser()
    root.mkdir(parents=True, exist_ok=True)
    return root


def _wrap_fragment(fragment: str, title: str) -> str:
    escaped_title = html.escape(title or "ArgusAI PoC")
    return f"""<!doctype html>
<html lang="zh-CN">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{escaped_title}</title>
  <style>
    body {{ font: 14px/1.6 system-ui, -apple-system, Segoe UI, sans-serif; margin: 24px; }}
    code, pre {{ font-family: Consolas, Monaco, monospace; }}
    pre {{ background: #f5f7fb; border: 1px solid #d8dee9; border-radius: 8px; padding: 12px; overflow: auto; }}
    .hint {{ color: #667085; }}
  </style>
</head>
<body>
  <h1>{escaped_title}</h1>
  <p class="hint">Generated by ArgusAI. Only use this page against authorized targets.</p>
{fragment}
</body>
</html>
"""


def create_poc_page(
    html_content: str,
    *,
    title: str = "ArgusAI PoC",
    filename: str = "",
    wrap: bool = True,
    open_browser: bool = False,
    base_dir: str = "",
) -> dict[str, Any]:
    """Write an assistant-generated PoC HTML file under the user data dir."""
    content = str(html_content or "")
    if not content.strip():
        return {"ok": False, "error": "html_content is required"}
    if len(content) > MAX_HTML_CHARS:
        return {"ok": False, "error": f"html_content too large; max {MAX_HTML_CHARS} chars"}
    page_title = str(title or "ArgusAI PoC")[:MAX_TITLE_CHARS]
    if wrap and "<html" not in content.lower():
        content = _wrap_fragment(content, page_title)
    safe_name = _safe_slug(filename or page_title)
    suffix = f"{int(time.time())}-{uuid.uuid4().hex[:8]}"
    root = _poc_dir(base_dir)
    path = root / f"{safe_name}-{suffix}.html"
    path.write_text(content, encoding="utf-8")
    uri = path.resolve().as_uri()
    opened = False
    if open_browser:
        opened = webbrowser.open(uri)
    return {
        "ok": True,
        "path": str(path),
        "directory": str(root),
        "uri": uri,
        "opened": opened,
        "title": page_title,
        "size": len(content),
    }


def open_poc_page(path_or_uri: str, *, base_dir: str = "") -> dict[str, Any]:
    """Open an existing PoC page if it lives under ArgusAI's PoC directory."""
    value = str(path_or_uri or "").strip()
    if not value:
        return {"ok": False, "error": "path_or_uri is required"}
    root = _poc_dir(base_dir).resolve()
    if value.startswith("file://"):
        from urllib.parse import unquote, urlparse

        path = Path(unquote(urlparse(value).path))
    else:
        path = Path(value)
    try:
        resolved = path.resolve()
    except Exception as e:
        return {"ok": False, "error": str(e)}
    if root not in resolved.parents and resolved != root:
        return {"ok": False, "error": f"refusing to open file outside PoC directory: {root}"}
    if not resolved.exists() or resolved.suffix.lower() not in {".html", ".htm"}:
        return {"ok": False, "error": "PoC page not found or not an HTML file"}
    uri = resolved.as_uri()
    return {"ok": True, "path": str(resolved), "uri": uri, "opened": webbrowser.open(uri)}

