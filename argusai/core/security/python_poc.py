"""Generate a one-click Python PoC bundle.

A reverse-engineering session typically ends with the AI saying "here's
how to reproduce the attack." The user then has to copy-paste 3-5 code
blocks across multiple Markdown sections, install ad-hoc requirements,
and hope the bits hang together. This module emits a self-contained
directory the user can ``cd`` into and run:

    poc/
      ├─ run.py           ← entry point (parses CLI args, runs the chain)
      ├─ requirements.txt ← pinned deps
      ├─ README.md        ← what it does, how to run it
      └─ helpers/         ← any extra modules the AI generated

The output lives under the assistant session sandbox (so the user can
inspect / edit / re-open in their file manager) or under the reverse
job's artifacts directory.
"""

from __future__ import annotations

import logging
import textwrap
from pathlib import Path
from typing import Any

log = logging.getLogger("argusai.python_poc")


DEFAULT_README = """\
# {title}

{description}

## How to run

```bash
pip install -r requirements.txt
python run.py {usage_args}
```

## What this does

{walkthrough}

## Generated by

argusai AI assistant, session {session_id}
"""


def _normalise_requirements(reqs: Any) -> list[str]:
    """Accept a list or a newline-string and normalise to one-per-line."""
    if reqs is None:
        return []
    if isinstance(reqs, str):
        items = [r.strip() for r in reqs.splitlines() if r.strip()]
    elif isinstance(reqs, list):
        items = [str(r).strip() for r in reqs if str(r).strip()]
    else:
        items = []
    # De-dup preserving order.
    seen = set()
    out = []
    for r in items:
        if r not in seen:
            seen.add(r)
            out.append(r)
    return out


def _normalise_helpers(helpers: Any) -> list[tuple[str, str]]:
    """Helpers come in as either ``[(name, content), ...]`` (list of
    pairs) or ``{name: content, ...}`` (dict).
    """
    if helpers is None:
        return []
    if isinstance(helpers, dict):
        return [(str(k), str(v)) for k, v in helpers.items() if k and v]
    if isinstance(helpers, list):
        out = []
        for item in helpers:
            if isinstance(item, dict) and "name" in item and "content" in item:
                out.append((str(item["name"]), str(item["content"])))
            elif isinstance(item, (list, tuple)) and len(item) == 2:
                out.append((str(item[0]), str(item[1])))
        return out
    return []


def _safe_filename(name: str) -> str:
    keep = "".join(c for c in name if c.isalnum() or c in "._-")
    return keep or "helper"


def lint_python_source(src: str, filename: str = "snippet.py") -> list[str]:
    """Static checks for fragility patterns we keep seeing in AI-generated Python.

    These are *warnings*, never blockers — the caller still gets the file
    written / the snippet executed. We only nudge the AI / the user toward
    writing scripts that don't silently swallow their failure mode.

    Reusable across :func:`_lint_poc_source` (PoC bundles) and the snippet
    runner (single-shot Python tools), so any new rule lands in one place.
    """

    warnings: list[str] = []
    if not src:
        return warnings

    has_try = "try:" in src
    mentions_pip_install = (
        '"install"' in src
        or "'install'" in src
        or ' install ' in src
        or 'pip install' in src
    ) and "pip" in src

    if ".json()" in src and not has_try:
        warnings.append(
            f"{filename}: 调用了 .json() 但全文没有 try/except；"
            "服务器返回 HTML/空 body 时会抛 JSONDecodeError 终止脚本。"
            "建议先看 Content-Type，再用 try/except 包住。"
        )

    if "requests." in src and "timeout=" not in src:
        warnings.append(
            f"{filename}: 出现 requests 调用但没有 timeout=，目标失联时脚本会无限挂起。"
        )

    if src.count("def ") >= 3 and not has_try and "except" not in src:
        warnings.append(
            f"{filename}: 定义了多个函数但全文没有任何 try/except，"
            "任一步异常都会让整个 PoC 中断。建议在 __main__ 主流程里"
            "为每个 case 加 try/except 包装，单点失败不影响其它 case。"
        )

    if "verify=False" in src and "InsecureRequestWarning" not in src:
        warnings.append(
            f"{filename}: 使用了 verify=False 但没禁用 InsecureRequestWarning，"
            "运行时会刷很多警告日志。建议加 urllib3.disable_warnings()。"
        )

    # ``pip install -q`` / ``--quiet`` silences pip's stderr on failure
    # too. Combined with ``subprocess.check_call`` (which raises
    # ``CalledProcessError`` with no captured output) the operator sees
    # only "returned non-zero exit status 1" and has no clue what broke.
    # This was the exact failure mode in the user's paramiko screenshot.
    if mentions_pip_install and ("-q" in src or "--quiet" in src):
        warnings.append(
            f"{filename}: pip install 使用了 -q / --quiet，安装失败时 stderr 会被静默，"
            "用户看到的只有 'non-zero exit status'，无法定位真正错误。"
            "建议去掉 -q 并用 subprocess.run([...], capture_output=True, text=True)，"
            "失败时主动打印 stdout/stderr。"
        )

    # ``subprocess.check_call`` doesn't capture child stdout/stderr; on
    # non-zero exit the raised ``CalledProcessError`` carries no message.
    # For pip / package installers this is especially bad because the
    # whole point of running it is to see *why* the install failed.
    if "subprocess.check_call" in src and mentions_pip_install:
        warnings.append(
            f"{filename}: 使用 subprocess.check_call 安装 pip 包时不会捕获 stderr，"
            "失败仅抛 CalledProcessError 无任何报错信息。"
            "建议改用 subprocess.run([...], capture_output=True, text=True)，"
            "并在 returncode != 0 时打印 result.stdout + result.stderr。"
        )

    return warnings


def _lint_poc_source(run_py_src: str, helpers: list[tuple[str, str]]) -> list[str]:
    """Bundle-level wrapper around :func:`lint_python_source`.

    Empirical motivation: a real Sakurairo info-disclosure PoC crashed on
    ``r.json()`` for the ``/gallery`` endpoint because the server returned
    HTML, which killed every step after it; later, an AI snippet did
    ``subprocess.check_call(["pip", "install", "paramiko", "-q"])`` and
    swallowed pip's actual error message, leaving the operator unable to
    explain why paramiko did not install.
    """

    warnings: list[str] = []
    sources: list[tuple[str, str]] = [("run.py", run_py_src)]
    sources.extend(helpers)
    for filename, src in sources:
        warnings.extend(lint_python_source(src, filename=filename))
    return warnings


def create_python_poc(
    *,
    out_dir: Path,
    title: str = "PoC",
    description: str = "",
    walkthrough: str = "",
    run_py: str = "",
    requirements: Any = None,
    helpers: Any = None,
    usage_args: str = "",
    session_id: str = "",
    overwrite: bool = False,
) -> dict[str, Any]:
    """Materialise a Python PoC bundle on disk.

    Args:
        out_dir: Target directory; created if missing.
        title: Project title for the README.
        description: One-paragraph description.
        walkthrough: Markdown bullet list of what the PoC does step-by-step.
        run_py: The ``run.py`` source code. Required.
        requirements: List of pip requirements (or newline-separated string).
        helpers: Optional extra files — dict ``{filename: content}`` or
            list of ``(name, content)`` tuples. Stored under ``helpers/``.
        usage_args: README example CLI tail, e.g. ``--target https://...``.
        session_id: Identifier for the README's footer (for traceability).
        overwrite: If false, fail when ``out_dir`` already has ``run.py``.

    Returns:
        ``{ok, out_dir, files_written, total_bytes, run_command}``.
    """
    run_py_src = (run_py or "").strip()
    if not run_py_src:
        return {"ok": False, "error": "run_py source is required"}

    out_dir = Path(out_dir)
    try:
        out_dir.mkdir(parents=True, exist_ok=True)
    except Exception as e:
        return {"ok": False, "error": f"could not create out_dir: {e}"}

    run_path = out_dir / "run.py"
    if run_path.exists() and not overwrite:
        return {
            "ok": False,
            "error": f"run.py already exists at {run_path}. Pass overwrite=true to replace.",
        }

    reqs = _normalise_requirements(requirements)
    helpers_list = _normalise_helpers(helpers)

    files_written: list[dict[str, Any]] = []
    total_bytes = 0

    def _write(path: Path, content: str) -> None:
        nonlocal total_bytes
        data = content if content.endswith("\n") else content + "\n"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(data, encoding="utf-8")
        size = len(data.encode("utf-8"))
        total_bytes += size
        files_written.append({"path": str(path), "size_bytes": size})

    # run.py — make sure there's a shebang and that it'll actually be
    # executed by a CPython that has the requirements installed.
    if not run_py_src.startswith("#!") and not run_py_src.lstrip().startswith("#"):
        run_py_src = "#!/usr/bin/env python3\n" + run_py_src
    _write(run_path, run_py_src)

    # requirements.txt.
    if reqs:
        _write(out_dir / "requirements.txt", "\n".join(reqs))
    else:
        _write(out_dir / "requirements.txt", "# (no third-party requirements)")

    # helpers/.
    for name, content in helpers_list:
        safe = _safe_filename(name)
        _write(out_dir / "helpers" / safe, content)

    # README.md.
    readme = DEFAULT_README.format(
        title=(title or "PoC").strip(),
        description=(description or "Reverse-engineering proof of concept generated by argusai.").strip(),
        usage_args=(usage_args or "").strip(),
        walkthrough=(walkthrough or "(no walkthrough provided)").strip(),
        session_id=(session_id or "(unknown)"),
    )
    _write(out_dir / "README.md", readme)

    lint_warnings = _lint_poc_source(run_py_src, helpers_list)
    if lint_warnings:
        log.warning("create_python_poc lint warnings (%d): %s", len(lint_warnings), lint_warnings)

    result: dict[str, Any] = {
        "ok": True,
        "out_dir": str(out_dir),
        "files_written": files_written,
        "total_bytes": total_bytes,
        "run_command": f"cd {out_dir} && pip install -r requirements.txt && python run.py {usage_args}".strip(),
        "next_steps": [
            "Tell the user where the PoC was written (out_dir) and how to run it.",
            "Optionally call ``sandbox_open_file(path='README.md')`` so they can open it.",
        ],
    }
    if lint_warnings:
        result["lint_warnings"] = lint_warnings
        result["next_steps"].insert(
            0,
            "lint_warnings 非空：建议根据警告改写 PoC（兜底 .json()、加 timeout、为每个 case 套 try/except），再用 overwrite=true 重新落盘。",
        )
    return result
